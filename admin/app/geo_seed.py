def _assert_unique() -> None:
    codes = ["ALL"]
    for code, _, _, countries in TREE:
        codes.append(code)
        codes.extend(item[0] for item in countries)
    dup = sorted({c for c in codes if codes.count(c) > 1})
    if dup:
        raise RuntimeError("国家地区编码重复: " + ",".join(dup))


_assert_unique()


def ensure_geo(db: Session) -> None:
    """表里还没有国家地区时写入整棵树。已有任意一行就不再补。"""
    if db.scalar(select(func.count()).select_from(GeoNode)):
        return
    root = GeoNode(parent_id=0, code="ALL", name_zh="全球", name_en="World", is_leaf=0, sort_order=0)
    db.add(root)
    db.flush()
    for i, (code, zh, en, countries) in enumerate(TREE, start=1):
        continent = GeoNode(parent_id=root.id, code=code, name_zh=zh, name_en=en, is_leaf=0, sort_order=i)
        db.add(continent)
        db.flush()
        for j, (cc, cz, ce) in enumerate(countries, start=1):
            db.add(GeoNode(parent_id=continent.id, code=cc, name_zh=cz, name_en=ce, is_leaf=1, sort_order=j))
    db.commit()
